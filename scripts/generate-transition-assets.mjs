import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const transitionDirectory = path.join(projectRoot, "public", "transition");
const outputPath = path.join(projectRoot, "src", "components", "pageTransitionAssets.ts");

const groups = [
  { folder: "almonds", kind: "primary" },
  { folder: "cashew", kind: "primary" },
  { folder: "pistachio", kind: "primary" },
  { folder: "pumpkin-seed", kind: "secondary" },
  { folder: "raisin", kind: "secondary" },
  { folder: "cranberry", kind: "secondary" },
];

function readPngDimensions(buffer, filePath) {
  const signature = buffer.subarray(0, 8).toString("hex");
  if (signature !== "89504e470d0a1a0a") throw new Error(`Expected a PNG file: ${filePath}`);
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
}

const assets = [];
for (const group of groups) {
  const directory = path.join(transitionDirectory, group.folder);
  const files = (await readdir(directory)).filter((file) => file.endsWith(".png")).sort();

  for (const file of files) {
    const filePath = path.join(directory, file);
    const { width, height } = readPngDimensions(await readFile(filePath), filePath);
    assets.push({
      id: file.replace(".png", ""),
      src: `/transition/${group.folder}/${file}`,
      width,
      height,
      kind: group.kind,
    });
  }
}

const source = `// This file is generated by scripts/generate-transition-assets.mjs.\n// PNG IHDR dimensions are read from public/transition on every dev/build startup.\n\nexport type TransitionAsset = {\n  id: string;\n  src: string;\n  width: number;\n  height: number;\n  kind: \"primary\" | \"secondary\";\n};\n\nexport const transitionAssets = ${JSON.stringify(assets, null, 2)} as const satisfies readonly TransitionAsset[];\n\nexport const primaryIngredients = transitionAssets.filter((asset) => asset.kind === \"primary\");\nexport const secondaryIngredients = transitionAssets.filter((asset) => asset.kind === \"secondary\");\n`;

await writeFile(outputPath, source, "utf8");
console.log(`Generated ${path.relative(projectRoot, outputPath)} from ${assets.length} native PNG files.`);
